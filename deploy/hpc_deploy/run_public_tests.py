#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""run_public_tests.py — Step 08: 超算侧「全局测试 + 公共 public 子场景测试」。

★ 执行位置：**超算环境**（远端 .venv-hpc-nce 内），本脚本只做 SSH 驱动。
★ 真实仿真**通过 sbatch 提交作业**（不在登录节点直接跑）。

两阶段（都在远端完成，哨兵文件判定完成 → 跨登录节点安全）
────────────────────────────────────────────────────────────
阶段 A（登录节点，快速，不需 FLASH 二进制）
  A1 三套全局 pytest：test/ 、flash/input_gen/test/ 、flash/output_processors/test/
  A2 public 场景输入生成 + 依赖/关联自检（gen_checker）：
       center_evolution/ch_center        （LaserSlab1D，CH 靶 + He 侧）
       sandwich/grad_dens_sandwich        （HE-CH-Si-CH-HE 渐变密度）
       sandwich/thin_layer_sandwich_si   （Si/CH/He 三层靶）
     ★ 生成目录（flash_input/ sim_input*/）被 .gitignore 排除 ⇒ 远端 clone
       后必须现场生成；这一步同时验证「干净克隆可一键生成输入」。

阶段 B（提交 sbatch 作业，串行）
  B1 每个 public 场景：**复用该场景自带的 submit_flash.sh**（内含正确的
     FLASH setup 标志，不重写 setup flags），只做三处补丁：
       ① SBATCH 输出路径 → 并行盘 WORK/out/（★ 绝不用 /tmp）
       ② 运行目录 R=/tmp/... → 并行盘（/tmp 是计算节点本地盘，作业结束即丢）
       ③ par 的 tmax/dtmax → 极短值（1e-11 / 1e-13，只验证「能跑出 chk」）
     然后 sbatch 提交 → sacct 轮询到终态 → 统计 chk 数。
  B2 逐场景给出判定：
       PASS       n_h5 > 0
       KNOWN_LIMIT 撞已知站点限制（QC 树 Intel MPI 运行期符号错误，
                    docs/FLASH三模式运行体系.md §8）→ 不改判 PASS，如实记录
       FAIL       其他失败（编译失败 / 作业 FAILED / 无 chk）

用法
  python run_public_tests.py                          # A + B（全部 3 场景）
  python run_public_tests.py --phase-a                # 只跑阶段 A（不提交作业）
  python run_public_tests.py --scenes ch_center       # 指定场景
  python run_public_tests.py --timeout 14400

铁律
  * 中间文件一律落 $HOME 并行盘，绝不用 /tmp（跨登录节点不可见）；
  * 超算 SSH 限并发 ⇒ 全程单会话串行，场景间不并发提交；
  * 提交前必查 squeue（父进程网络死亡 ≠ 远端作业结束）。
"""
