def main(argv=None) -> int:
    import argparse

    ap = argparse.ArgumentParser(
        prog="SandwichTxN/__init__.py",
        description="sandwich_txn 自包含场景: 独立运行/分析 "
                    "(runs → <本目录>/runs/<run_id>)")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_run = sub.add_parser("run", help="运行 FLASH 仿真")
    p_run.add_argument("--nproc", type=int, default=4, help="MPI 进程数 (默认 4)")
    p_run.add_argument("--run-id", default=None, help="显式 run_id (默认自动 6 位递增)")
    p_run.add_argument("--timeout", type=int, default=1800, help="FLASH 超时秒数")
    p_run.add_argument("--mode", default=None,
                       help="执行目标 auto/local/wsl (WSL 内运行用 local)")
    p_run.add_argument("--force-recompile", action="store_true")
    p_ana = sub.add_parser("analyze", help="分析 run 产物 (缺省 = 本场景最新 run)")
    p_ana.add_argument("run_dir", nargs="?", default=None,
                       help="run 目录或其 sim_output (缺省 = 本场景最新 run)")
    p_gen = sub.add_parser("gen", help="(重新)生成 sim_input_si 输入")
    p_gen.add_argument("--force", action="store_true", help="删除后全量重新生成")
    p_gen.add_argument("--tmax", default="",
                       help="覆盖 .par 的 tmax [s] (极短验证, 如 1e-11)")
    args = ap.parse_args(argv)

    if args.cmd == "gen":
        d = _HERE / "sim_input_si"
        if args.force:
            shutil.rmtree(d, ignore_errors=True)
        scenario_txn.ensure_sim_input()
        if args.tmax:
            params = dict(scenario_txn.default_params)
            params["tmax"] = float(args.tmax)
            (d / f"{SIM_NAME}.par").write_text(
                _build_par_clojure(params), encoding="utf-8", newline="\n")
            print(f"[gen] tmax override: {args.tmax} s")
        return 0

    if args.cmd == "run":
        from flash.scenarios.core.simulator import FlashSimulatorEngine
        engine = FlashSimulatorEngine(scenario_txn)
        res = engine.run(
            runs_dir=str(_HERE / "runs"),
            run_id=args.run_id,
            mpi_nproc=args.nproc,
            flash_timeout=args.timeout,
            force_recompile=args.force_recompile,
            mode=args.mode,
        )
        print(f"[run] success={res.success}  n_chk={res.n_chk}  "
              f"run_dir={res.run_dir}")
        if not res.success:
            print(f"[run] FAIL: {res.error_message}")
            return 1
        return 0

    if args.cmd == "analyze":
        import subprocess
        script = _HERE / "scripts" / "analyze_output.py"
        cmd = [sys.executable, str(script)]
        if args.run_dir:
            cmd.append(args.run_dir)
        return subprocess.run(cmd).returncode

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
