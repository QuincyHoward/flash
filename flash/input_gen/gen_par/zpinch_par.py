_COMMENT_COL = 80   # 注释起始列 (与官方 par 风格一致)


def render_zpinch_par(params, comments=None, sections=None) -> str:
    """渲染 par 文本。params 值为 par 字面量字符串; comments 键→注释。"""
    comments = comments if comments is not None else ZPINCH_PAR_COMMENTS
    sections = sections if sections is not None else ZPINCH_PAR_SECTIONS
    out = []
    first = True
    for title, items in sections:
        if not first:
            out.append("")
        if title:
            out.append("#" * 26)
            out.append("#" + " " * 24 + "#")
            out.append("#" + f"     {title}".ljust(24) + "#")
            out.append("#" + " " * 24 + "#")
            out.append("#" * 26)
        first = False
        keys = [k for kind, k in items if kind == "param"]
        w = max((len(k) for k in keys), default=1)
        for kind, x in items:
            if kind == "comment":
                out.append(x)
                continue
            val = params[x]
            line = f"{x:<{w}} = {val}"
            cmt = comments.get(x)
            if cmt:
                line = line.ljust(_COMMENT_COL - 2) + "# " + cmt
            out.append(line)
    return "\n".join(out) + "\n"


def build_zpinch_par(overrides=None) -> str:
    """构建 ZPinch par 文本。

    overrides: {键: 字面量字符串 | (字面量, 行尾注释)}。
    """
    params = dict(ZPINCH_BASELINE)
    comments = dict(ZPINCH_PAR_COMMENTS)
    for k, v in (overrides or {}).items():
        if isinstance(v, tuple):
            params[k], comments[k] = v
        else:
            params[k] = v
    return render_zpinch_par(params, comments, ZPINCH_PAR_SECTIONS)
