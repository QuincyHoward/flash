def pulse_from_params(params: Dict[str, Any]) -> Dict[str, list]:
    """从参数集里抽取 82 段激光脉冲波形 {times:[s], powers:[W/cm^2]}。

    ★ 波形只存一份真源 (``LAYER_TRACER_BASELINE`` 的 ed_time_1_*/ed_power_1_*),
      这里的函数用于绘图/诊断等只读场景, 避免第二份硬编码副本漂移。
    """
    idx = sorted(int(k.rsplit("_", 1)[1]) for k in params
                 if k.startswith("ed_time_1_"))
    return {
        "times": [float(params[f"ed_time_1_{i}"]) for i in idx],
        "powers": [float(params[f"ed_power_1_{i}"]) for i in idx],
    }
