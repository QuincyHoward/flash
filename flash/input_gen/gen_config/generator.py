"""
FLASH Config 文件生成器 (自包含)
═════════════════════════════════

Config 内容从 LaserSlab/Config 模板提取后硬编码。
"""

from pathlib import Path
from typing import Any, List, Optional, Union


def _build_multi_species_config(species_defs: List[dict], simulation_path: str) -> str:
    """从物种定义列表生成多物种 Config。

    为每个物种注册几何 (radius/height)、热物理量 (rho/tele/tion/trad)、
    zmin、eos 类型/子类型/表文件、ms 原子量/序数、opacity 参数，并声明
    DATAFILES。

    Args:
        species_defs: 形如 [{"name": "cham", "file": ..., "rho": ...,
            "A": ..., "Z": ..., "radius": ..., "height": ...}, ...]
        simulation_path: 仿真路径标识（用于注释）
    """
    lines = [
        f"# Configuration file for {simulation_path} simulation",
        "# Generated by ConfigGenerator (multi-species)",
        "REQUIRES Driver",
        "REQUIRES physics/Hydro",
        "",
        "USESETUPVARS ThreeT",
        "",
        "IF ThreeT",
        "   REQUESTS physics/Diffuse/DiffuseMain/Unsplit",
        "",
        "   REQUESTS physics/sourceTerms/Heatexchange/HeatexchangeMain/Spitzer",
        "   REQUESTS physics/materialProperties/Conductivity/ConductivityMain/SpitzerHighZ",
        "ENDIF",
        "",
        "# Setup example:",
        "#   ./setup -auto <用户名>/LaserSlab1d_new -1d +cartesian -nxb=16 \\",
        "#           -maxblocks=1024 +hdf5typeio species=<comma,species> \\",
        "#           +mtmmmt +laser +uhd3t +mgd mgd_meshgroups=10",
        "",
    ]

    # DATAFILES (去重)
    datafiles = []
    seen = set()
    for sp in species_defs:
        if sp.get("file") and sp["file"] not in seen:
            seen.add(sp["file"])
            datafiles.append(sp["file"])
    for f in datafiles:
        lines.append(f"DATAFILES {f}")
    lines.append("")

    lines.append("##########################")
    lines.append("#                        #")
    lines.append("#   RUNTIME PARAMETERS   #")
    lines.append("#                        #")
    lines.append("##########################")
    lines.append("")

    lines.append('D sim_initGeom Use a spherical target if sphere, default to slab')
    lines.append('PARAMETER sim_initGeom STRING "slab" ["slab","sphere"]')
    lines.append("")

    for sp in species_defs:
        name = sp["name"]
        cap = name.capitalize()
        lines.append(f"# {cap} material defaults:")
        rad = sp.get("radius_param") or f"sim_{name}Radius"
        hei = sp.get("height_param") or f"sim_{name}Height"
        if "radius" in sp and sp["radius"] is not None:
            lines.append(f"D {rad} The radius of the {name} layer")
            lines.append(f"PARAMETER {rad} REAL {sp.get('radius', 0.0)}")
        if "height" in sp and sp["height"] is not None:
            lines.append(f"D {hei} The height of the {name} layer")
            lines.append(f"PARAMETER {hei} REAL {sp.get('height', 0.0)}")
        lines.append(f"D sim_rho{cap} Initial {name} density")
        lines.append(f"PARAMETER sim_rho{cap}   REAL {sp.get('rho', 1.0)}")
        lines.append(f"D sim_tele{cap} Initial {name} electron temperature")
        lines.append(f"PARAMETER sim_tele{cap}  REAL {sp.get('tele', 290.11375)}")
        lines.append(f"D sim_tion{cap} Initial {name} ion temperature")
        lines.append(f"PARAMETER sim_tion{cap}  REAL {sp.get('tion', 290.11375)}")
        lines.append(f"D sim_trad{cap} Initial {name} radiation temperature")
        lines.append(f"PARAMETER sim_trad{cap}  REAL {sp.get('trad', 290.11375)}")
        lines.append(f"D sim_zmin{cap} {name} minimum zbar allowed")
        lines.append(f"PARAMETER sim_zmin{cap}  REAL 0.0")
        lines.append(f"D sim_eos{cap} {name} EOS type")
        lines.append(f'PARAMETER sim_eos{cap}   STRING "eos_tab" ["eos_tab","eos_gam"]')
        lines.append(f"D ms_{name}A {name} atomic weight")
        lines.append(f"PARAMETER ms_{name}A REAL {sp.get('A', 1.0)}")
        lines.append(f"D ms_{name}Z {name} atomic number")
        lines.append(f"PARAMETER ms_{name}Z REAL {sp.get('Z', 1.0)}")
        if sp.get("file"):
            lines.append(f"D eos_{name}EosType {name} EOS type")
            lines.append(f'PARAMETER eos_{name}EosType STRING "eos_tab" ["eos_tab","eos_gam"]')
            lines.append(f"D eos_{name}SubType {name} EOS subtype")
            lines.append(f'PARAMETER eos_{name}SubType STRING "ionmix4"')
            lines.append(f"D eos_{name}TableFile {name} EOS table file")
            lines.append(f'PARAMETER eos_{name}TableFile STRING "{sp["file"]}"')
            lines.append(f"D op_{name}Absorb {name} opacity absorption mode")
            lines.append(f'PARAMETER op_{name}Absorb STRING "op_tabpa"')
            lines.append(f"D op_{name}Emiss {name} opacity emission mode")
            lines.append(f'PARAMETER op_{name}Emiss STRING "op_tabpe"')
            lines.append(f"D op_{name}Trans {name} opacity transmission mode")
            lines.append(f'PARAMETER op_{name}Trans STRING "op_tabro"')
            lines.append(f"D op_{name}FileType {name} opacity file type")
            lines.append(f'PARAMETER op_{name}FileType STRING "ionmix4"')
            lines.append(f"D op_{name}FileName {name} opacity table file")
            lines.append(f'PARAMETER op_{name}FileName STRING "{sp["file"]}"')
        lines.append("")

    lines.append('D lase_variable saves (density of) the irradiated energy from EnergyDeposition unit, cf. RP ed_irradVarName')
    lines.append('VARIABLE lase TYPE: PER_VOLUME')
    lines.append("")

    return "\n".join(lines)


