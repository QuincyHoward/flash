class ConfigGenerator:
    """FLASH Config 文件生成器 (自包含)。

    从硬编码的默认模板生成 Config 内容。
    """

    def __init__(self):
        self.default_content = DEFAULT_CONFIG_CONTENT

    def generate(
        self,
        simulation_path: str = "hello/LaserSlab1d_new",
        target_material: Any = None,
        chamber_gas: Any = None,
        extra_datafiles: Optional[List[str]] = None,
        include_thomson: bool = False,
        species_defs: Optional[List[dict]] = None,
    ) -> str:
        """生成 Config 文件内容。

        Args:
            simulation_path: 仿真路径标识（用于注释）
            target_material: 靶材 Material 对象（预留，暂不处理）
            chamber_gas: 腔室气体 Material 对象（预留，暂不处理）
            extra_datafiles: 额外的 DATAFILES
            include_thomson: 是否包含 Thomson 散射诊断
            species_defs: 物种定义列表。若提供，生成多物种 Config。

        Returns:
            Config 文件内容字符串
        """
        if species_defs:
            content = _build_multi_species_config(species_defs, simulation_path)
            if extra_datafiles:
                content += "\n" + "\n".join(f"DATAFILES {f}" for f in extra_datafiles) + "\n"
            if include_thomson:
                content += """
USESETUPVARS ThscDemo
IF ThscDemo
   REQUIRES diagnostics/ThomsonScattering
   VARIABLE pwin
   VARIABLE pwia
   VARIABLE pwde
   VARIABLE pwd1
   VARIABLE pwi2
   VARIABLE pwd2
ENDIF
"""
            return content

        content = self.default_content

        # 替换 DATAFILES 部分
        datafiles = set()
        if target_material is not None and hasattr(target_material, 'file'):
            datafiles.add(target_material.file)
        if chamber_gas is not None and hasattr(chamber_gas, 'file'):
            datafiles.add(chamber_gas.file)
        if datafiles:
            # 重建 content 中的 DATAFILES 行
            lines = content.split("\n")
            new_lines = []
            in_datafiles = False
            added_datafiles = False
            for line in lines:
                if line.startswith("DATAFILES"):
                    if not in_datafiles:
                        in_datafiles = True
                        for f in sorted(datafiles):
                            new_lines.append(f"DATAFILES {f}")
                        added_datafiles = True
                    continue
                elif in_datafiles and not line.startswith("DATAFILES"):
                    in_datafiles = False
                if not added_datafiles and in_datafiles:
                    continue
                new_lines.append(line)
            if not added_datafiles:
                # 插入 DATAFILES 行
                insert_idx = 0
                for i, line in enumerate(new_lines):
                    if "REQUIRES" in line:
                        insert_idx = i + 1
                datafile_lines = [f"DATAFILES {f}" for f in sorted(datafiles)]
                new_lines[insert_idx:insert_idx] = datafile_lines
            content = "\n".join(new_lines)

        if extra_datafiles:
            lines = content.split("\n")
            for f in extra_datafiles:
                lines.append(f"DATAFILES {f}")
            content = "\n".join(lines)

        if include_thomson:
            content += """

USESETUPVARS ThscDemo
IF ThscDemo
   REQUIRES diagnostics/ThomsonScattering
   VARIABLE pwin
   VARIABLE pwia
   VARIABLE pwde
   VARIABLE pwd1
   VARIABLE pwi2
   VARIABLE pwd2
ENDIF
"""

        return content

    def save(
        self,
        output_path: Union[str, Path],
        simulation_path: str = "hello/LaserSlab1d_new",
        target_material: Any = None,
        chamber_gas: Any = None,
        extra_datafiles: Optional[List[str]] = None,
        include_thomson: bool = False,
        species_defs: Optional[List[dict]] = None,
    ) -> Path:
        """生成并保存 Config 文件。"""
        content = self.generate(
            simulation_path=simulation_path,
            target_material=target_material,
            chamber_gas=chamber_gas,
            extra_datafiles=extra_datafiles,
            include_thomson=include_thomson,
            species_defs=species_defs,
        )
        out = Path(output_path)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8", newline="\n")
        return out
