"""FEOS 核心输入生成与运行模块

提供 FEOSInputGen 类，支持：
- .par 输入卡参数设置与生成
- 单次运行 (run_single)
- 批量运行 (batch_run)
- 自动文件名生成（Z{Z:02d}_{x:.2f}[-Z...] 规范，无群数后缀）
- Material-Number 预检（FEOS_Material-DB.dat）
- WSL 编译/运行（feos 为 C++ ELF，Makefile 默认 g++）

FEOS 16.7 by Dr. Steffen Faik（GPL v3），vendored 于 ../src/FEOS/
布局一手依据: src/FEOS/Code/FE-03_MAIN.C + COMMON-00_DEFINITS.H
"""

import os
import re
import shutil
import subprocess
import datetime
from typing import Dict, List, Any, Optional, Tuple


class FEOSInputGen:
    """FEOS 输入卡生成与运行类"""

    # vendored FEOS 包目录（feos_run/../src/FEOS）
    FEOS_SRC_DIR = os.path.normpath(
        os.path.join(os.path.dirname(__file__), "..", "src", "FEOS"))
    FEOS_CODE_DIR = os.path.join(FEOS_SRC_DIR, "Code")
    FEOS_DATA_DIR = os.path.join(FEOS_SRC_DIR, "EOS-Data")

    # 运行时数据文件（FEOS 硬编码 CWD 相对路径 ./FEOS_Material-DB.dat /
    # ./FEOS_TF-Table_1197.dat，见 LIB-00_DEFINITS.H —— 必须拷入 workdir）
    RUNTIME_DATA_FILES = ("FEOS_Material-DB.dat", "FEOS_TF-Table_1197.dat")

    PARAM_DESCRIPTIONS = {
        'material_number': '材料编号（FEOS_Material-DB.dat 中的条目号，1000-9999）',
        'maxwell_flag': '是否做 Maxwell 两相构建（0: 否, 1: 是）',
        'softsphere_flag': '低密度区用软球函数替换 TF 冷曲线（0: 否, 1: 是）',
        'user_calculations_flag': '是否执行用户自定义计算（Hugoniot 等，0/1）',
        'rhonorm': '密度归一化基准 Rho_norm (g/cm^3)',
        'rhoratio': '各十进制区间内对数分布的密度点数 Rhoratio{x}, x=-6..6',
        'tnorm': '温度归一化基准 T_norm (eV)',
        'tratio': '各十进制区间内对数分布的温度点数 Tratio{x}, x=-6..6',
    }

    # vendored 示例（Al.par/SiO2.par）默认点分布
    DEFAULT_RHORATIO = {-6: 0, -5: 3, -4: 3, -3: 3, -2: 10, -1: 50,
                        0: 50, 1: 50, 2: 10, 3: 3, 4: 3, 5: 3, 6: 3}
    DEFAULT_TRATIO = {-6: 1, -5: 2, -4: 10, -3: 20, -2: 20, -1: 10,
                      0: 2, 1: 1, 2: 1, 3: 1, 4: 0, 5: 0, 6: 0}

    def __init__(self):
        """初始化生成器"""
        self.parameters: Dict[str, Any] = {}
        self.comments: Dict[str, str] = {}
        self.elements: List[Tuple[float, float]] = []   # [(Z, X), ...]
        self.current_example = ""

    # ------------------------------------------------------------------
    # 参数设置
    # ------------------------------------------------------------------
    def set_parameter(self, name: str, value: Any, index: int = None) -> None:
        """设置参数值；index 用于 rhoratio/tratio 的区间号（-6..6）"""
        key = f"{name}{index}" if index is not None else name
        self.parameters[key] = value
        if name in self.PARAM_DESCRIPTIONS:
            self.comments[key] = self.PARAM_DESCRIPTIONS[name]

    def set_ratio_distribution(self, kind: str, mapping: Dict[int, int]) -> None:
        """便捷设置点分布字典，kind = 'rhoratio' 或 'tratio'"""
        for x, n in mapping.items():
            self.set_parameter(kind, n, x)

    def set_elements(self, elements: List[Tuple[float, float]]) -> None:
        """设置组成列表 [(Z, X), ...]（X=每分子原子数；用于输出命名与 cn4 头部）"""
        self.elements = [(float(z), float(x)) for z, x in elements]

    def clear_parameters(self) -> None:
        """清除所有参数"""
        self.parameters.clear()
        self.comments.clear()
        self.elements.clear()
        self.current_example = ""

    def _dict_to_parameters(self, params_dict: dict) -> None:
        """将参数字典还原为内部参数。

        支持两种 value 类型:
        - 标量: {'material_number': 3717}
        - 带区间索引字典: {'rhoratio': {-2: 10, -1: 50, ...}}
        特殊键: '_elements' (组成列表), '_name' (示例名)
        """
        self.clear_parameters()
        self.current_example = params_dict.get('_name', '')
        for key, value in params_dict.items():
            if key.startswith('_'):
                if key == '_elements':
                    self.set_elements(value)
                continue
            if isinstance(value, dict):
                self.set_ratio_distribution(key, value)
            else:
                self.set_parameter(key, value)

    def _format_value(self, value: Any) -> str:
        """格式化参数值为字符串（对齐 vendored Al.par 风格）"""
        if isinstance(value, float):
            if abs(value) >= 1e4 or (0 < abs(value) < 1e-2):
                return f"{value:.6e}"
            return f"{value:g}"
        return str(value)

    # ------------------------------------------------------------------
    # .par 生成
    # ------------------------------------------------------------------
    def generate_par(self, output_dir: str, basename: str = "feos_input") -> str:
        """生成 FEOS .par 输入卡（仅表生成所需的 Computation-Settings 与 Q-table 两节）"""
        def get(name, default=None):
            return self.parameters.get(name, default)

        lines = []
        mat = get('material_number')
        lines.append("%% This file contains all the data needed for")
        lines.append("%% computing an EOS for a material in the material db")
        lines.append("%% Generated by Python FEOSInputGen (FEOS 16.7, Steffen Faik)")
        if self.current_example:
            lines.append(f"%% Material example: {self.current_example}")
        lines.append("")
        lines.append("                   Computation-Settings")
        lines.append("")
        lines.append(f"Material-Number = {self._format_value(mat)}"
                     f"       % {self.comments.get('material_number', '')}")
        flag_keys = (('maxwell_flag', 'Maxwell_Flag', '"Maxwell construction" desired?'),
                     ('softsphere_flag', 'SoftSphere_Flag',
                      'Replace TF cold curve for densities < Rsolid with soft sphere?'),
                     ('user_calculations_flag', 'UserCalculations_Flag',
                      'Perform user-defined calculations?'))
        for key, label, note in flag_keys:
            lines.append(f"{label} = {self._format_value(get(key, 1))}"
                         f"             % {note} (0: no, 1: yes)")
        lines.append("")
        lines.append("%%%%%%%%%%%%%%%%%%%%%%%%")
        lines.append("")
        lines.append("                   Q-table")
        lines.append("")
        lines.append("% Distribution of densities:")
        lines.append(f"Rhonorm = {self._format_value(float(get('rhonorm', 1.0)))}"
                     f"     % {self.comments.get('rhonorm', '')}")
        rhoratio = get('rhoratio', self.DEFAULT_RHORATIO)
        for x in range(-6, 7):
            n = rhoratio.get(x, 0)
            lines.append(f"Rhoratio{x} = {n:<4d} % {self.comments.get('rhoratio', '')}"
                         if x in rhoratio else f"Rhoratio{x} = {n:<4d}")
        lines.append("")
        lines.append("% Distribution of temperatures:")
        lines.append(f"Tnorm = {self._format_value(float(get('tnorm', 1.0e3)))}"
                     f"     % {self.comments.get('tnorm', '')}")
        tratio = get('tratio', self.DEFAULT_TRATIO)
        for x in range(-6, 7):
            n = tratio.get(x, 0)
            lines.append(f"Tratio{x} = {n:<4d} % {self.comments.get('tratio', '')}"
                         if x in tratio else f"Tratio{x} = {n:<4d}")
        lines.append("")
        lines.append("%%%% eof.")

        content = "\n".join(lines) + "\n"
        os.makedirs(output_dir, exist_ok=True)
        filepath = os.path.join(output_dir, f"{basename}.par")
        with open(filepath, 'w', encoding='utf-8', newline='\n') as f:
            f.write(content)
        return content

    # ------------------------------------------------------------------
    # 命名
    # ------------------------------------------------------------------
    def _make_basename(self, elements: Optional[List[Tuple[float, float]]] = None) -> str:
        """从组成生成文件名 basename。

        格式: Z{Z:02d}_{x:.2f}（单元）或 Z{Z:02d}_{x:.2f}-Z...（混合物，x 为
        每分子原子数归一化后的原子分数）。FEOS 不产不透明度，故无群数后缀。
        """
        elements = elements or self.elements
        if not elements:
            raise KeyError("缺少组成信息：请 set_elements([...]) 或在 params_dict 传 '_elements'")
        total_x = sum(x for _z, x in elements)
        parts = [f"Z{int(round(z)):02d}_{x / total_x:.2f}" for z, x in elements]
        return "-".join(parts)

    def _get_timestamp(self) -> str:
        """获取当前时间戳（%Y%m%d_%H%M）"""
        return datetime.datetime.now().strftime("%Y%m%d_%H%M")

    # ------------------------------------------------------------------
    # Material-DB 预检
    # ------------------------------------------------------------------
    @classmethod
    def read_material_db(cls, db_path: str = None) -> Dict[int, dict]:
        """解析 FEOS_Material-DB.dat，返回 {material_number: {'A':.., 'Z':.., 'X':..}}"""
        db_path = db_path or os.path.join(cls.FEOS_DATA_DIR, "FEOS_Material-DB.dat")
        db: Dict[int, dict] = {}
        pat_sesame = re.compile(r"\[(\d+)\]_SESAME-Number")
        pat_a = re.compile(r"\[(\d+)\]_A\[(\d+)\]\s*=\s*([0-9.eE+-]+)")
        pat_z = re.compile(r"\[(\d+)\]_Z\[(\d+)\]\s*=\s*([0-9.eE+-]+)")
        pat_x = re.compile(r"\[(\d+)\]_X\[(\d+)\]\s*=\s*([0-9.eE+-]+)")
        with open(db_path, encoding='utf-8', errors='replace') as f:
            for line in f:
                m = pat_sesame.search(line)
                if m:
                    db.setdefault(int(m.group(1)), {'A': [], 'Z': [], 'X': []})
                for pat, field in ((pat_a, 'A'), (pat_z, 'Z'), (pat_x, 'X')):
                    m = pat.search(line)
                    if m:
                        no = int(m.group(1))
                        idx = int(m.group(2)) - 1
                        entry = db.setdefault(no, {'A': [], 'Z': [], 'X': []})
                        while len(entry[field]) <= idx:
                            entry[field].append(None)
                        entry[field][idx] = float(m.group(3))
        return db

    def _check_material_number(self, matno: int) -> dict:
        """预检 Material-Number 是否存在于 Material-DB，缺失即抛错并列出可用条目"""
        db = self.read_material_db()
        if matno not in db:
            avail = ", ".join(str(n) for n in sorted(db))
            raise KeyError(
                f"Material-Number {matno} 不在 FEOS_Material-DB.dat 中。"
                f"可用条目: {avail}")
        return db[matno]

    # ------------------------------------------------------------------
    # WSL 编译 / 运行
    # ------------------------------------------------------------------
    def _ensure_feos_binary(self) -> str:
        """确保 feos 二进制存在（Code/feos 优先，其次 EOS-Data/feos）；缺失则 WSL make 编译"""
        candidates = [os.path.join(self.FEOS_CODE_DIR, "feos"),
                      os.path.join(self.FEOS_DATA_DIR, "feos")]
        for c in candidates:
            if os.path.exists(c) and os.path.getsize(c) > 0:
                return c
        print("  [*] feos 二进制缺失，WSL make all 编译中（g++ -O3）...")
        wsl_code = self._win_to_wsl(self.FEOS_CODE_DIR)
        result = subprocess.run(["wsl", "--cd", wsl_code, "make", "all"],
                                capture_output=True, text=True, timeout=300)
        if result.returncode != 0:
            hint = (result.stderr or result.stdout or "").strip()[:500]
            raise RuntimeError(f"FEOS make 编译失败 (rc={result.returncode}): {hint}\n"
                               "提示: WSL 需安装 g++ 与 make（sudo apt install g++ make）")
        for c in candidates:
            if os.path.exists(c) and os.path.getsize(c) > 0:
                print("  [+] 编译成功")
                return c
        raise RuntimeError("FEOS make 编译后仍未找到 feos 二进制")

    def _copy_feos_binaries(self, dest_dir: str) -> str:
        """拷贝 feos 二进制与两个运行时数据文件到工作目录（FEOS 按 CWD 相对路径读取）"""
        binary = self._ensure_feos_binary()
        shutil.copy2(binary, os.path.join(dest_dir, "feos"))
        for fname in self.RUNTIME_DATA_FILES:
            shutil.copy2(os.path.join(self.FEOS_DATA_DIR, fname),
                         os.path.join(dest_dir, fname))
        return os.path.join(dest_dir, "feos")

    @staticmethod
    def _win_to_wsl(win_path: str) -> str:
        """转换 Windows 绝对路径为 WSL 路径"""
        abs_path = os.path.abspath(win_path)
        drive = abs_path[0].lower()
        return f"/mnt/{drive}{abs_path[2:].replace(os.sep, '/')}"

    def _wsl_run(self, work_dir: str, args: List[str]) -> subprocess.CompletedProcess:
        """通过 WSL 在工作目录运行 feos（Linux ELF 二进制）"""
        wsl_path = self._win_to_wsl(work_dir)
        subprocess.run(["wsl", "--cd", wsl_path, "chmod", "+x", "feos"],
                       capture_output=True, text=True)
        cmd = ["wsl", "--cd", wsl_path, "./feos", *args]
        return subprocess.run(cmd, capture_output=True, text=True, timeout=600)

    @staticmethod
    def _find_runtime_error(work_dir: str) -> str:
        """从运行日志中查找 FEOS/LIB 运行时错误标记"""
        for log in ("_stderr.log", "_stdout.log"):
            path = os.path.join(work_dir, log)
            if os.path.exists(path):
                with open(path, errors='replace') as f:
                    content = f.read(4000)
                for marker in ("FE-ERROR", "LIB-ERROR", "ME-ERROR"):
                    if marker in content:
                        idx = content.find(marker)
                        return content[idx:idx + 150].strip()
        return ""

    # ------------------------------------------------------------------
    # 清理
    # ------------------------------------------------------------------
    def _clean_output_folder(self, folder_path: str, basename: str) -> None:
        """清理文件夹，只保留二进制、运行时数据、.par 与 .feos 产物"""
        keep_exact = {"feos", *self.RUNTIME_DATA_FILES, f"{basename}.par"}
        if not os.path.exists(folder_path):
            return
        for item_name in os.listdir(folder_path):
            if item_name in keep_exact or item_name.endswith(".feos") \
                    or item_name.endswith(".cn4"):
                continue
            item_path = os.path.join(folder_path, item_name)
            try:
                if os.path.isfile(item_path) or os.path.islink(item_path):
                    os.remove(item_path)
                elif os.path.isdir(item_path):
                    shutil.rmtree(item_path)
            except Exception as e:
                print(f"清理 {item_name} 时出错: {e}")

    # ------------------------------------------------------------------
    # 单次 / 批量运行
    # ------------------------------------------------------------------
    def run_single(self, params_dict: dict, output_base_dir: str) -> str:
        """对单个参数字典执行一次完整的 FEOS 流程

        Args:
            params_dict: 参数字典（material_number/rhonorm/rhoratio/...，
                可含 '_elements' 组成列表与 '_name' 示例名）
            output_base_dir: 输出基础目录

        Returns:
            str: 生成的 .feos 文件绝对路径（失败返回 ""）
        """
        # 1. 还原参数
        self._dict_to_parameters(params_dict)
        matno = int(self.parameters['material_number'])

        # 2. 组成：显式给出优先，否则从 Material-DB 反查
        elements = self.elements or None
        mat_info = self._check_material_number(matno)
        if elements is None:
            elements = list(zip(mat_info['Z'], mat_info['X']))

        # 3. basename 与工作目录
        basename = self._make_basename(elements)
        timestamp = self._get_timestamp()
        folder_name = f"{basename}-{timestamp}"
        work_dir = os.path.join(output_base_dir, folder_name)
        os.makedirs(work_dir, exist_ok=True)

        # 4. 拷贝二进制与运行时数据
        self._copy_feos_binaries(work_dir)

        # 5. 生成 .par（feos CLI 接收不带 .par 后缀的名字）
        self.generate_par(work_dir, basename)

        # 6. 运行 FEOS（通过 WSL）
        error_log = ""
        try:
            result = self._wsl_run(work_dir, [basename])
            if result.returncode != 0:
                print(f"  [!] feos 返回码: {result.returncode}")
            for name, text in (("_stdout.log", result.stdout),
                               ("_stderr.log", result.stderr)):
                if text:
                    with open(os.path.join(work_dir, name), 'w',
                              encoding='utf-8', newline='\n') as ef:
                        ef.write(text)
            if result.stderr and result.stderr.strip():
                error_log = result.stderr.strip()
                print(f"  [!] stderr: {error_log[:300]}")
        except subprocess.TimeoutExpired:
            print("  [!] feos 运行超时")
        except Exception as e:
            print(f"  [!] 运行异常: {e}")

        # 7. 重命名 .feos 产物，检测 0 字节
        raw_feos = os.path.join(work_dir, f"{basename}.feos")
        feos_filename = f"{basename}-{timestamp}.feos"
        feos_path = os.path.join(work_dir, feos_filename)
        if os.path.exists(raw_feos):
            size = os.path.getsize(raw_feos)
            os.rename(raw_feos, feos_path)
            if size > 0:
                print(f"  [+] 输出: {feos_filename}  ({size:,} bytes)")
            else:
                err_hint = self._find_runtime_error(work_dir)
                print(f"  [!] 输出为空: {feos_filename} (0 bytes)"
                      + (f" — {err_hint}" if err_hint else ""))
        else:
            err_hint = self._find_runtime_error(work_dir)
            print(f"  [!] {basename}.feos 未生成"
                  + (f" — {err_hint}" if err_hint else "，检查 _stdout.log"))
            feos_path = ""

        # 8. 清理工作目录
        self._clean_output_folder(work_dir, basename)

        return feos_path

    def batch_run(self, params_list: List[dict], output_base_dir: str) -> List[str]:
        """批量执行多个参数字典的 FEOS 流程

        Returns:
            List[str]: 生成的 .feos 文件路径列表
        """
        os.makedirs(output_base_dir, exist_ok=True)
        results = []
        total = len(params_list)
        for i, params_dict in enumerate(params_list, 1):
            name = params_dict.get('_name', f'任务{i}')
            print(f"[{i}/{total}] {name} ...")
            feos_path = self.run_single(params_dict, output_base_dir)
            results.append(feos_path)
            print(f"[{i}/{total}] 完成: {feos_path}")
            print()
        return results
